"""
Reproducible acquisition & checksum verification utility for the genuine public
Caltrans PeMS District 8 (PEMS08) traffic dataset published under CC-BY-4.0 on Zenodo
(DOI: 10.5281/zenodo.7816008).

No synthetic data or placeholder measurements are ever generated by this module.
"""

from __future__ import annotations

import hashlib
import json
import os
import shutil
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict

import numpy as np
import requests


ZENODO_RECORD_ID = "7816008"
ZENODO_DOI = "10.5281/zenodo.7816008"
ZENODO_DOCUMENTATION_URL = "https://zenodo.org/records/7816008"
ZENODO_LICENSE = "Creative Commons Attribution 4.0 International (CC-BY-4.0)"

PEMS08_NPZ_URL = f"https://zenodo.org/api/records/{ZENODO_RECORD_ID}/files/PEMS08.npz/content"
PEMS08_CSV_URL = f"https://zenodo.org/api/records/{ZENODO_RECORD_ID}/files/PEMS08.csv/content"

# Exact verified byte sizes from Zenodo record 7816008 API metadata
EXPECTED_SIZES = {
    "PEMS08.npz": 18525419,
    "PEMS08.csv": 4032,
}

DEFAULT_PUBLIC_DATA_DIR = Path(__file__).resolve().parents[2] / "data" / "public"


def compute_sha256(file_path: Path) -> str:
    """Compute SHA-256 hex digest of a local file."""
    digest = hashlib.sha256()
    with open(file_path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _download_file(url: str, dest: Path, timeout_seconds: int = 120) -> None:
    tmp_path = dest.with_suffix(dest.suffix + ".part")
    with requests.get(url, stream=True, timeout=timeout_seconds) as resp:
        resp.raise_for_status()
        with open(tmp_path, "wb") as fh:
            for chunk in resp.iter_content(chunk_size=1024 * 1024):
                if chunk:
                    fh.write(chunk)
    shutil.move(str(tmp_path), str(dest))


def download_pems08(
    target_dir: Path | str | None = None,
    force: bool = False,
) -> Dict[str, Any]:
    """
    Download and validate the official Zenodo PEMS08 dataset files (PEMS08.npz + PEMS08.csv).
    Writes verified integrity metadata to pems08_metadata.json.
    """
    out_dir = Path(target_dir) if target_dir else DEFAULT_PUBLIC_DATA_DIR
    out_dir.mkdir(parents=True, exist_ok=True)

    npz_path = out_dir / "PEMS08.npz"
    csv_path = out_dir / "PEMS08.csv"
    meta_path = out_dir / "pems08_metadata.json"

    for fname, url, dest in [
        ("PEMS08.npz", PEMS08_NPZ_URL, npz_path),
        ("PEMS08.csv", PEMS08_CSV_URL, csv_path),
    ]:
        if force or not dest.exists() or dest.stat().st_size != EXPECTED_SIZES[fname]:
            _download_file(url, dest)
        actual_size = dest.stat().st_size
        if actual_size != EXPECTED_SIZES[fname]:
            raise RuntimeError(
                f"Downloaded {fname} has unexpected size {actual_size} bytes "
                f"(expected {EXPECTED_SIZES[fname]} bytes)."
            )

    # Verify tensor dimensions & non-corruption
    with np.load(npz_path) as archive:
        if "data" not in archive:
            raise ValueError("PEMS08.npz missing expected array key 'data'.")
        arr = archive["data"]
        if arr.shape != (17856, 170, 3):
            raise ValueError(f"PEMS08.npz has unexpected shape {arr.shape}; expected (17856, 170, 3).")

    metadata = {
        "dataset_id": "pems08_public",
        "dataset_name": "Caltrans PeMS08 Freeway Traffic Benchmark (Zenodo)",
        "is_simulated": False,
        "is_genuine_public": True,
        "ps003_eligible": True,
        "original_source": "California Department of Transportation (Caltrans) Performance Measurement System (PeMS), District 8 (San Bernardino)",
        "distribution_source": f"Zenodo TrafficDataSets (DOI: {ZENODO_DOI})",
        "creator": "Shiqi Zhang (Zhengzhou University, ORCID: 0000-0001-9940-8409)",
        "publication_date": "2023-04-11",
        "documentation_url": ZENODO_DOCUMENTATION_URL,
        "reference_paper": "Guo et al., Attention Based Spatial-Temporal Graph Convolutional Networks for Traffic Flow Forecasting, AAAI 2019",
        "license": ZENODO_LICENSE,
        "license_id": "cc-by-4.0",
        "start_timestamp": "2016-07-01T00:00:00",
        "end_timestamp": "2016-08-31T23:55:00",
        "sampling_interval_minutes": 5,
        "time_steps": 17856,
        "sensors_count": 170,
        "channels": [
            {"index": 0, "name": "flow", "unit": "veh/5m", "description": "Total vehicle flow passing loop detector per 5-minute interval"},
            {"index": 1, "name": "occupy", "unit": "ratio [0,1]", "description": "Average lane occupancy fraction per 5-minute interval"},
            {"index": 2, "name": "speed", "unit": "mph", "description": "Mean vehicle speed reported in miles per hour"},
        ],
        "files": {
            "PEMS08.npz": {
                "url": PEMS08_NPZ_URL,
                "size_bytes": npz_path.stat().st_size,
                "sha256": compute_sha256(npz_path),
            },
            "PEMS08.csv": {
                "url": PEMS08_CSV_URL,
                "size_bytes": csv_path.stat().st_size,
                "sha256": compute_sha256(csv_path),
            },
        },
        "verified_at": datetime.now(timezone.utc).isoformat(),
    }

    with open(meta_path, "w", encoding="utf-8") as fh:
        json.dump(metadata, fh, indent=2)

    return metadata


if __name__ == "__main__":
    info = download_pems08()
    print(json.dumps(info, indent=2))
